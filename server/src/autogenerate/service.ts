// Starting and reading batch autogenerate jobs (OpenSpec change `batch-autogenerate`, design D2,
// D14; api-contract-freeze "Batch autogenerate job object", "Batch autogenerate endpoints"). The
// routes call these with the request's principal; `startAutogenerateJob` is also the hand-off for a
// server-side caller with a given initiator (proposal "Follow-up": the playlist import's
// "autogenerate after import"), so it re-runs every start check itself, in the start route's
// order. Every read and write runs under the principal's binding: the database proves the
// initiator manages the team when the job commits (D2).

import type {
  AutogenerateDetailItem,
  AutogenerateJobSummary,
  AutogenerateScope,
} from '@autologger/catalog';
import {
  AUTOGENERATE_DETAIL,
  AUTOGENERATE_LLM_STEPS,
  AUTOGENERATE_STEPS,
  type AutogenerateBlocked,
  type AutogenerateDetailResponse,
  type AutogenerateJobWire,
  type AutogeneratePreviewResponse,
  type AutogenerateScopeBody,
  type AutogenerateStartBody,
  type AutogenerateStep,
  autogenerateOutcomeDetail,
} from '@autologger/contract';
import { resolveSttCredential } from '../auth/providerResolve';
import { runFeatureAllowed } from '../env';
import { callerLlmRoute } from '../generation/aiRoute';
import { type GenerationPrincipal, RUN_FEATURE_FORBIDDEN_DETAIL } from '../generation/principal';

/** A refusal: the status and the exact body the start route answers. */
export interface AutogenerateRefusal {
  status: 400 | 403 | 404 | 409 | 503;
  body: Record<string, unknown>;
}

const iso = (ms: number | null): string | null => (ms === null ? null : new Date(ms).toISOString());
const name = (u: GenerationPrincipal['user']) => `${u.given_name} ${u.family_name}`.trim();

/** The job object (api-contract-freeze "Batch autogenerate job object"). */
export function jobWire(j: AutogenerateJobSummary): AutogenerateJobWire {
  return {
    id: j.id,
    team_id: j.team_id,
    status: j.status,
    stop_reason: j.stop_reason as AutogenerateJobWire['stop_reason'],
    scope: j.scope,
    show_ids: j.show_ids,
    steps: AUTOGENERATE_STEPS.filter((s) => j.steps.includes(s)),
    wiki_mode: j.wiki_mode,
    initiator_id: j.initiator_user_id,
    initiator_name: j.initiator_name,
    cancel_requested_by_name: j.cancel_requested_by_name,
    cancel_requested_at_utc: iso(j.cancel_requested_at_ms),
    created_at_utc: iso(j.created_at_ms) as string,
    started_at_utc: iso(j.started_at_ms),
    finished_at_utc: iso(j.finished_at_ms),
    sessions: j.session_count,
    counts: j.counts,
    current: j.current,
  };
}

const ENDED = new Set(['done', 'skipped', 'failed', 'cancelled']);

/** The detail's per-session items, in processing order. */
export function detailWire(
  job: AutogenerateJobSummary,
  items: AutogenerateDetailItem[],
): AutogenerateDetailResponse {
  const sessions: AutogenerateDetailResponse['sessions'] = [];
  for (const i of items) {
    let s = sessions.at(-1);
    if (s === undefined || s.session_id !== i.session_id) {
      s = {
        session_id: i.session_id,
        title: i.title,
        show_id: i.show_id,
        effective_date: i.effective_date,
        ordinal: i.ordinal,
        steps: [],
      };
      sessions.push(s);
    }
    const ownOutput = i.step === 'events' || i.step === 'topics';
    s.steps.push({
      step: i.step,
      status: i.status,
      outcome:
        i.outcome as AutogenerateDetailResponse['sessions'][number]['steps'][number]['outcome'],
      detail: autogenerateOutcomeDetail(i.outcome),
      wiki_accepted: i.step === 'wiki' && i.status === 'done' ? (i.wiki_accepted ?? 0) : null,
      wiki_pending: i.step === 'wiki' && i.status === 'done' ? (i.wiki_pending ?? 0) : null,
      kept_edited: ownOutput && ENDED.has(i.status) ? (i.kept_edited ?? 0) : null,
    });
  }
  return { job: jobWire(job), sessions };
}

function scopeOf(body: AutogenerateScopeBody): AutogenerateScope {
  return body.show_ids ? { showIds: body.show_ids } : { sessionIds: body.session_ids ?? [] };
}

/** The first reason the principal could not start this job now, in the start route's order. */
async function blockedFor(
  p: GenerationPrincipal,
  steps: readonly AutogenerateStep[],
): Promise<AutogenerateBlocked | null> {
  if (steps.includes('transcript') && (await resolveSttCredential(p.env, p.user.id)) === null) {
    return 'unconfigured-stt';
  }
  if (
    steps.some((s) => AUTOGENERATE_LLM_STEPS.includes(s)) &&
    (await callerLlmRoute(p.env, p.user)) === null
  ) {
    return 'unconfigured-llm';
  }
  if (!runFeatureAllowed(p.env.config, p.user)) return 'not-approved';
  return null;
}

/** The scope's candidates, or the scope refusal (404 show or session, 400 none or too many). */
async function candidates(
  p: GenerationPrincipal,
  teamId: string,
  body: AutogenerateScopeBody,
): Promise<{ ids: string[] } | AutogenerateRefusal> {
  const r = await p.catalog.autogenerate.resolveScope(teamId, scopeOf(body));
  if (!r.ok) {
    return {
      status: 404,
      body: {
        detail:
          r.reason === 'show-not-found'
            ? AUTOGENERATE_DETAIL.showNotFound
            : AUTOGENERATE_DETAIL.sessionNotFound,
      },
    };
  }
  if (r.sessions.length === 0)
    return { status: 400, body: { detail: AUTOGENERATE_DETAIL.noSessions } };
  if (r.sessions.length > 1000)
    return { status: 400, body: { detail: AUTOGENERATE_DETAIL.tooMany } };
  return { ids: r.sessions.map((s) => s.id) };
}

/** The preview (the estimate): writes nothing. The role check is the route's. */
export async function previewAutogenerateJob(
  p: GenerationPrincipal,
  teamId: string,
  body: AutogenerateScopeBody,
): Promise<AutogeneratePreviewResponse | AutogenerateRefusal> {
  const c = await candidates(p, teamId, body);
  if ('status' in c) return c;
  const steps = AUTOGENERATE_STEPS.filter((s) => body.steps.includes(s));
  const missing = await p.catalog.autogenerate.previewMissing(c.ids);
  const runs: AutogeneratePreviewResponse['runs'] = {};
  for (const s of steps) runs[s] = s === 'wiki' ? c.ids.length : missing[s];
  return {
    sessions: c.ids.length,
    steps,
    runs,
    max_runs: c.ids.length * steps.length,
    blocked: await blockedFor(p, steps),
  };
}

/** Starts a job for the principal as its initiator, after every start check in the route's
 * order (the role, the scope, the credentials, the approval, the live job, the confirmed count). */
export async function startAutogenerateJob(
  p: GenerationPrincipal,
  teamId: string,
  body: AutogenerateStartBody,
): Promise<{ job: AutogenerateJobWire } | AutogenerateRefusal> {
  const role = await p.catalog.auth.authGetMembershipRole(p.user.id, teamId);
  if (role === null) return { status: 404, body: { detail: 'Team not found' } };
  if (role !== 'owner' && role !== 'admin') {
    return { status: 403, body: { detail: 'Admin role required.' } };
  }
  const c = await candidates(p, teamId, body);
  if ('status' in c) return c;
  const blocked = await blockedFor(p, body.steps);
  if (blocked === 'unconfigured-stt') {
    return { status: 503, body: { detail: AUTOGENERATE_DETAIL.sttUnconfigured } };
  }
  if (blocked === 'unconfigured-llm') {
    return { status: 503, body: { detail: AUTOGENERATE_DETAIL.llmUnconfigured } };
  }
  if (blocked === 'not-approved')
    return { status: 403, body: { detail: RUN_FEATURE_FORBIDDEN_DETAIL } };
  const r = await p.catalog.autogenerate.createJob({
    teamId,
    initiatorId: p.user.id,
    initiatorName: name(p.user),
    scope: scopeOf(body),
    steps: body.steps,
    wikiMode: body.wiki_mode,
    expectedSessions: body.expected_sessions,
    nowMs: p.env.ports.clock.now(),
  });
  switch (r.kind) {
    case 'created':
      return { job: jobWire(r.job) };
    case 'live-job':
      return { status: 409, body: { detail: AUTOGENERATE_DETAIL.liveJob, job_id: r.jobId } };
    case 'sessions-changed':
      return {
        status: 409,
        body: { detail: AUTOGENERATE_DETAIL.sessionsChanged, sessions: r.sessions },
      };
    case 'show-not-found':
      return { status: 404, body: { detail: AUTOGENERATE_DETAIL.showNotFound } };
    case 'session-not-found':
      return { status: 404, body: { detail: AUTOGENERATE_DETAIL.sessionNotFound } };
    case 'no-sessions':
      return { status: 400, body: { detail: AUTOGENERATE_DETAIL.noSessions } };
    case 'too-many':
      return { status: 400, body: { detail: AUTOGENERATE_DETAIL.tooMany } };
  }
}

/** The cancel name snapshot (given and family name, never the email). */
export function cancelBy(p: GenerationPrincipal): { id: string; name: string } {
  return { id: p.user.id, name: name(p.user) };
}
