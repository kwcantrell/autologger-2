// The events step (OpenSpec change `batch-autogenerate`, design D6, D7 events, D9): the runner
// shared by `POST /api/sessions/:sessionId/events/generate` and the batch worker. Moved from the
// route unchanged: the configuration gate, the approved-user rule, the anchored-transcript and
// instruction preconditions, the aggregate instruction bound, the shared per-session AI slot and
// its `ai-turn` lease, the run snapshot and the one-shot turn. It returns a typed outcome instead
// of an HTTP answer; the route maps each outcome to its unchanged status and detail.
//
// For a batch step (`batch`), the run also:
// - asks `beforeRun(runId)` once the slot and lease are held, which re-checks the gap and records
//   the run id on the item (fenced on the job lease); `present` or `stop` ends the run before any
//   provider request;
// - excludes the events of the item's earlier attempts (`earlierRunIds`) from the prompt's
//   existing events and from `create_event`'s anchor basis, as a regenerate excludes its snapshot,
//   without being a regenerate;
// - after a success, deletes the events of every earlier attempt; after a failure, those of every
//   attempt, this one included. Each delete is per row with the insert-time version 1, as the
//   principal: an event a person edited is kept and counted (`keptEdited`).

