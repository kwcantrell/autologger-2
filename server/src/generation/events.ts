/** Map ONE raw (possibly legacy-loose) show-category JSON entry to the run
 * snapshot's category shape (ledger registration shape: id, name, type,
 * color, auto_instruction?, dropdown_options[{label, needs_context,
 * auto_instruction?}]). Defensive `String(...)`/shape guards mirror the other
 * raw-categories readers — stored categories normally come out of
 * `validateCategoriesList` normalization, but legacy JSON may be looser. */
function toGenerationSnapshotCategory(raw: unknown): AiGenerationSnapshotCategory {
  const rec = (raw && typeof raw === 'object' ? raw : {}) as Record<string, unknown>;
  const instr = typeof rec.auto_instruction === 'string' ? rec.auto_instruction.trim() : '';
  const optsRaw = Array.isArray(rec.dropdown_options) ? rec.dropdown_options : [];
  const dropdownOptions = optsRaw.flatMap((o): AiGenerationSnapshotOption[] => {
    if (typeof o === 'string') {
      const label = o.trim();
      return label ? [{ label, needs_context: false }] : [];
    }
    if (!o || typeof o !== 'object') return [];
    const or = o as Record<string, unknown>;
    const label = String(or.label ?? or.name ?? '').trim();
    if (!label) return [];
    const optInstr = typeof or.auto_instruction === 'string' ? or.auto_instruction.trim() : '';
    return [
      {
        label,
        needs_context: Boolean(or.needs_context ?? false),
        ...(optInstr ? { auto_instruction: optInstr } : {}),
      },
    ];
  });
  return {
    id: String(rec.id ?? ''),
    name: String(rec.name ?? ''),
    type: String(rec.type ?? '')
      .toUpperCase()
      .trim() as CategoryKind,
    color: String(rec.color ?? ''),
    ...(instr ? { auto_instruction: instr } : {}),
    dropdown_options: dropdownOptions,
  };
}

/** Aggregate pre-spawn instruction size over the snapshot (design D8, guard
 * 6). Generate All preserves the legacy entry count: every bearing category
 * plus every bearing DROPDOWN option. A filtered custom snapshot counts only
 * participating button-level instructions and selected instructed options.
 * `bytes` is the total UTF-8 size of every participating instruction. */
function instructionAggregate(
  categories: readonly AiGenerationSnapshotCategory[],
  countEveryCategory: boolean,
): {
  bytes: number;
  entries: number;
} {
  let bytes = 0;
  let entries = 0;
  for (const cat of categories) {
    if (countEveryCategory || cat.auto_instruction) entries += 1;
    if (cat.auto_instruction) {
      bytes += Buffer.byteLength(cat.auto_instruction, 'utf8');
    }
    if (cat.type !== 'DROPDOWN') continue;
    for (const opt of cat.dropdown_options) {
      if (!opt.auto_instruction) continue;
      entries += 1;
      bytes += Buffer.byteLength(opt.auto_instruction, 'utf8');
    }
  }
  return { bytes, entries };
}

function filterGenerationCategories(
  categories: readonly AiGenerationSnapshotCategory[],
  selection: EventGenerateBody['selection'],
): AiGenerationSnapshotCategory[] {
  if (!selection || selection.length === 0) return [...categories];

  const buttonIds = new Set(
    selection
      .filter((entry) => entry.option_label === undefined || entry.option_label === null)
      .map((entry) => entry.category_id),
  );
  const optionLabelsByCategory = new Map<string, Set<string>>();
  for (const entry of selection) {
    if (typeof entry.option_label !== 'string') continue;
    const labels = optionLabelsByCategory.get(entry.category_id) ?? new Set<string>();
    labels.add(entry.option_label);
    optionLabelsByCategory.set(entry.category_id, labels);
  }

  return categories.flatMap((category): AiGenerationSnapshotCategory[] => {
    const { auto_instruction: autoInstruction, ...base } = category;
    const selectedLabels = optionLabelsByCategory.get(category.id);
    const dropdownOptions =
      category.type === 'DROPDOWN' && selectedLabels
        ? category.dropdown_options.filter(
            (option) => selectedLabels.has(option.label) && Boolean(option.auto_instruction),
          )
        : [];
    const filtered: AiGenerationSnapshotCategory = {
      ...base,
      ...(buttonIds.has(category.id) && autoInstruction
        ? { auto_instruction: autoInstruction }
        : {}),
      dropdown_options: dropdownOptions,
    };
    return categoryIsInstructionBearing(filtered) ? [filtered] : [];
  });
}

/** Project the session's COMPLETE existing events for the snapshot categories
 * into the message builder's dedup-basis shape, in the feed's order
 * (`wall_time_utc ASC, id ASC`). Timecodes arrive already rendered by
 * `eventRowToRpc`'s `formatSmpte` path — the same rendering every event read
 * surface serves; `isAuto` reads `metadata_json.auto_generated`. */
function existingEventsForGenerate(
  events: readonly EventRpc[],
  categoryIds: ReadonlySet<string>,
): Record<string, EventGenerateExistingEvent[]> {
  const byCategory: Record<string, EventGenerateExistingEvent[]> = {};
  const sorted = [...events].sort((a, b) => {
    if (a.wall_time_utc !== b.wall_time_utc) return a.wall_time_utc < b.wall_time_utc ? -1 : 1;
    return a.event_id < b.event_id ? -1 : a.event_id > b.event_id ? 1 : 0;
  });
  for (const e of sorted) {
    if (!categoryIds.has(e.category)) continue;
    const isAuto = isAutoGeneratedMetadataJson(e.metadata_json);
    const rows = byCategory[e.category] ?? [];
    byCategory[e.category] = rows;
    rows.push({
      timecode: e.timecode ?? '',
      message: e.message,
      isAuto,
    });
  }
  return byCategory;
}

// ── own output (batch-autogenerate D7) ─────────────────────────────────────────────────────────

/** The run id an event's metadata carries, or null. */
function runIdOf(e: EventRpc): string | null {
  try {
    const m = JSON.parse(e.metadata_json || '{}') as Record<string, unknown>;
    return typeof m.auto_generate_run_id === 'string' ? m.auto_generate_run_id : null;
  } catch {
    return null;
  }
}

/** The session's events written by one of `runIds`, with their versions. */
export async function eventsOfRuns(
  p: GenerationPrincipal,
  sessionId: string,
  runIds: readonly string[],
): Promise<EventRpc[]> {
  if (runIds.length === 0) return [];
  const ids = new Set(runIds);
  const events = await (await hubFor(p, sessionId)).exportEvents();
  return events.filter((e) => {
    const r = runIdOf(e);
    return r !== null && ids.has(r);
  });
}

/** Deletes the events of `runIds`, one row at a time with the insert-time version 1, as the
 * principal (design D7 "Version-guarded deletes"): an event a person edited is kept. */
export async function deleteOwnEvents(
  p: GenerationPrincipal,
  sessionId: string,
  runIds: readonly string[],
): Promise<{ deleted: number; keptEdited: number }> {
  let deleted = 0;
  let keptEdited = 0;
  for (const e of await eventsOfRuns(p, sessionId, runIds)) {
    const r = await (await hubFor(p, sessionId)).deleteEvent(e.event_id, {
      version: 1,
      overwrite: false,
    });
    if ('conflict' in r) keptEdited += 1;
    else if (r.ok) deleted += 1;
  }
  return { deleted, keptEdited };
}

/** Whether the session has its auto-generated events (design D7 events): an auto-generated event
 * other than unedited recorded partial output (`recordedRunIds`, of any job's non-done item). */
export async function eventsPresent(
  p: GenerationPrincipal,
  sessionId: string,
  recordedRunIds: readonly string[],
): Promise<boolean> {
  const recorded = new Set(recordedRunIds);
  const events = await (await hubFor(p, sessionId)).exportEvents();
  return events.some((e) => {
    if (!isAutoGeneratedMetadataJson(e.metadata_json)) return false;
    const r = runIdOf(e);
    return !(r !== null && recorded.has(r) && e.version === 1);
  });
}

// ── the runner ─────────────────────────────────────────────────────────────────────────────────

export type EventsPrecondition =
  | 'no-transcript'
  | 'no-anchors'
  | 'no-instructions'
  | 'too-many-instructions';

export type EventsOutcome =
  | { kind: 'unconfigured' }
  | { kind: 'forbidden' }
  | { kind: 'precondition'; code: EventsPrecondition; detail: string }
  | { kind: 'busy' }
  /** batch: `beforeRun` found the output present under the slot. */
  | { kind: 'present' }
  /** batch: `beforeRun` could not record the run id (the job lease is lost); nothing ran. */
  | { kind: 'stopped' }
  | { kind: 'failed'; rateLimited: boolean; providerFailed: boolean; keptEdited: number }
  | { kind: 'ok'; created: number; capHit: boolean; deleted?: number; keptEdited: number };

export interface EventsBatchOptions {
  /** The item's earlier attempts' run ids. */
  earlierRunIds: readonly string[];
  /** Under the slot, before the turn: re-check the gap and record `runId` on the item. */
  beforeRun: (runId: string) => Promise<'go' | 'present' | 'stop'>;
}

export interface EventsRunOptions {
  row: Row;
  selection?: EventGenerateBody['selection'];
  regenerate?: boolean;
  /** The manual regenerate's delete of its snapshot, run under the slot after a success that
   * created events; returns the deleted count (the route's `session-undo` step). */
  deleteRegenerateSnapshot?: (ids: string[]) => Promise<number>;
  batch?: EventsBatchOptions;
}

export async function runEvents(
  p: GenerationPrincipal,
  sessionId: string,
  opts: EventsRunOptions,
): Promise<EventsOutcome> {
  const config = p.env.config;
  // 2. Configuration gate — before any spawn or model request (a run spends the principal's
  // provider budget, or the operator's CLI subscription, and writes into the session): the
  // principal's route (ai-sdk-agent-harness D1).
  const route = await callerLlmRoute(p.env, p.user);
  if (route === null) return { kind: 'unconfigured' };
  // 2b. Approved users only (run-status-and-sweeper D9).
  if (!runFeatureAllowed(config, p.user)) return { kind: 'forbidden' };

  // The show's categories are read BEFORE the word snapshot below, so the
  // snapshot-to-registration window holds no storage call or await
  // (async-session-callers D4). Their checks still run in step 4's order.
  const rawCategories =
    (await p.catalog.sessions.getSessionShowCategories(sessionId))?.categories ?? [];

  // 3. Anchored-transcript precondition — a run without session-time anchors
  // could only invent timecodes. This read doubles as the run's WORD SNAPSHOT
  // (spec "snapshot at run start"; Phase-3 review carry): once it resolves, no
  // storage call or other `await` occurs before the per-session slot is
  // acquired below. The prologue's event export after the slot is a separate
  // hub read, so the run's word and event snapshots can come from two
  // committed states when another handler resumes in the same tick
  // (async-session-hub design D7, S11).
  const transcriptWords = await (await hubFor(p, sessionId)).listTranscriptWords();
  if (transcriptWords.length === 0) {
    return {
      kind: 'precondition',
      code: 'no-transcript',
      detail: EVENT_GENERATE_NO_TRANSCRIPT_DETAIL,
    };
  }
  if (!transcriptWords.some((w) => String(w.session_time ?? '').trim() !== '')) {
    return { kind: 'precondition', code: 'no-anchors', detail: EVENT_GENERATE_NO_ANCHORS_DETAIL };
  }

  // 4. Instruction-bearing categories (the single imported definition, never
  // re-derived) — a show with none has nothing to detect.
  const bearing = rawCategories.filter(categoryIsInstructionBearing);
  if (bearing.length === 0) {
    return {
      kind: 'precondition',
      code: 'no-instructions',
      detail: EVENT_GENERATE_NO_INSTRUCTIONS_DETAIL,
    };
  }
  const categories = filterGenerationCategories(
    bearing.map(toGenerationSnapshotCategory),
    opts.selection,
  );
  if ((opts.selection?.length ?? 0) > 0 && categories.length === 0) {
    return {
      kind: 'precondition',
      code: 'no-instructions',
      detail: EVENT_GENERATE_NO_INSTRUCTIONS_DETAIL,
    };
  }

  // 5. Aggregate pre-spawn instruction bound (design D8) — either half
  // tripping fails fast, before the CLI ever spawns.
  const { bytes, entries } = instructionAggregate(categories, (opts.selection?.length ?? 0) === 0);
  const maxBytes = eventGenerateMaxInstructionBytes(config);
  const maxEntries = eventGenerateMaxInstructionEntries(config);
  if (bytes > maxBytes || entries > maxEntries) {
    return {
      kind: 'precondition',
      code: 'too-many-instructions',
      detail:
        `The show's generation instructions exceed the configured bound (${bytes} instruction bytes vs max ` +
        `${maxBytes}; ${entries} instruction-bearing entries vs max ${maxEntries}). Shorten or remove some ` +
        'instructions, or raise EVENT_GENERATE_MAX_INSTRUCTION_BYTES / EVENT_GENERATE_MAX_INSTRUCTION_ENTRIES.',
    };
  }

  // 6. Single-flight (per session), spawning nothing; no process-wide ceiling
  // (run-status-and-sweeper D2). Same registry as AI chat/AI v2/topics; released in this
  // runner's own finally.
  const proc = aiChatTurns.tryAcquire(sessionId);
  if (!proc.ok) return { kind: 'busy' };
  // The session's `ai-turn` lease (session-run-leases D4), claimed after the
  // await-free window above ended at the synchronous tryAcquire: a refusal means
  // another process runs a turn here, so it reads as session-busy.
  const slot = await claimAiLeaseFor(() => hubFor(p, sessionId), sessionId, proc);
  if (slot === null) return { kind: 'busy' };

  try {
    const runId = crypto.randomUUID();
    const batch = opts.batch;
    if (batch) {
      const go = await batch.beforeRun(runId);
      if (go === 'present') return { kind: 'present' };
      if (go === 'stop') return { kind: 'stopped' };
    }
    const hub = await hubFor(p, sessionId);
    const regenerate = opts.regenerate === true;
    // event-generate-hardening D2/D3 (gate ruling E3) — ONE hub.exportEvents()
    // read here, in the prologue before the turn starts, serves three purposes: (1) the
    // regenerate pre-spawn id SNAPSHOT (route-side JS predicate — no
    // dedicated store-side listing RPC, so the exclusion set and delete set
    // are the same array by construction), (2) the prompt's existing-events
    // enumeration with the snapshot excluded, and (3) the anchor-basis
    // exclusion threaded into the run context for create_event (D3). A
    // non-regenerate run sees the export untouched — byte-identical to today.
    // batch-autogenerate D7: a batch re-entry excludes its earlier attempts' events the same way.
    const exportedEvents = await hub.exportEvents();
    const snapshotIds = regenerate
      ? exportedEvents
          .filter((e) => isAutoGeneratedMetadataJson(e.metadata_json))
          .map((e) => e.event_id)
      : [];
    const earlier = new Set(batch?.earlierRunIds ?? []);
    const excludedIds = regenerate
      ? snapshotIds
      : earlier.size > 0
        ? exportedEvents
            .filter((e) => {
              const r = runIdOf(e);
              return r !== null && earlier.has(r);
            })
            .map((e) => e.event_id)
        : [];
    const excluded = excludedIds.length > 0 || regenerate ? new Set(excludedIds) : undefined;
    const eventsForPrompt = excluded
      ? exportedEvents.filter((e) => !excluded.has(e.event_id))
      : exportedEvents;

    // The RUN SNAPSHOT (spec "Single orchestrator turn"; ledger registration
    // shape), built ONCE pre-spawn. The SAME object feeds both the MCP turn
    // registration (create_event's allowlist/cap/anchoring inputs + the
    // rendering's word snapshot) and the message builder's enumeration —
    // mid-run show/session edits cannot affect the in-flight run.
    const ctx = timecodeCtx(opts.row);
    const cap = eventGenerateMaxCreatedEvents(config);
    const generation: AiGenerationRunContext = {
      runId,
      frameRate: ctx.frameRate,
      startOffsetFrames: ctx.startOffsetFrames,
      startedAtUtc: String(opts.row.started_at_utc ?? ''),
      cap,
      categories,
      words: transcriptWords.map((w) => ({
        word: String(w.word ?? ''),
        session_time: String(w.session_time ?? ''),
        speaker: String(w.speaker ?? ''),
      })),
      // D3 — threaded so create_event's anchor computation excludes the
      // doomed snapshot rows too; absent on non-regenerate runs.
      ...(excluded ? { regenerateSnapshotIds: excluded } : {}),
    };
    const message = buildEventGenerateMessage({
      categories,
      existingEventsByCategoryId: existingEventsForGenerate(
        eventsForPrompt,
        new Set(categories.map((cat) => cat.id)),
      ),
    });

    const common = {
      clock: p.env.ports.clock,
      registry: p.env.ports.sessions,
      caller: p.caller,
      sessionId,
      message,
      systemPrompt: EVENT_GENERATE_SYSTEM_PROMPT,
      mcpContext: { tools: EVENT_GENERATE_ALLOWED_TOOLS, generation },
      timeoutMs: eventGenerateTimeoutSec(config) * 1000,
      emit: () => {},
      // NO abortSignal — spec: a run always completes server-side regardless
      // of the initiating client's connection (the topics/generate D2
      // precedent); events land via event.changed broadcasts either way.
    };
    const outcome = await driveAiTurn(
      route.kind === 'cli'
        ? {
            ...common,
            cliPath: config.CLAUDE_CLI_PATH.trim(),
            allowedTools: EVENT_GENERATE_ALLOWED_TOOLS,
            maxBudgetUsd: eventGenerateMaxBudgetUsd(config),
          }
        : { ...common, sdk: sdkTurnSpec(p.env, route, 'events', generateSdkLimits(config)) },
    );
    // An AI SDK run's tool bodies may still be running after a timeout: wait for them before the
    // regenerate delete or the slot release (D3 "Draining tool bodies"). The lease keeps renewing.
    await outcome.toolsDrained?.();

    if (outcome.ok) {
      // A run that restarted at the smaller output cap (D3 "A smaller-model fallback") is noted,
      // content-free.
      if (outcome.outputCapFallback !== undefined) {
        console.info(
          `[events/generate] session=${sessionId}: AI turn succeeded${sdkFallbackSuffix(outcome)}`,
        );
      }
      // event-generate-hardening D2 (gate ruling E1) — delete-after-success:
      // destruction requires a replacement. A clean turn that created nothing
      // keeps the prior set and reports deleted:0. The delete goes through a
      // freshly re-acquired hub (the route's `session-undo` step), because the
      // turn just awaited for up to the configured timeout, and an idle hub
      // can be evicted and reopened meanwhile (async-session-hub design D6).
      const deleted = regenerate
        ? outcome.createdEvents > 0
          ? ((await opts.deleteRegenerateSnapshot?.(snapshotIds)) ?? 0)
          : 0
        : undefined;
      // batch-autogenerate D7: an interrupted partial set is never a complete run, so a success
      // deletes the events of every earlier attempt, even when this run created none.
      const kept = batch ? (await deleteOwnEvents(p, sessionId, [...earlier])).keptEdited : 0;
      return {
        kind: 'ok',
        created: outcome.createdEvents,
        capHit: outcome.createdEvents >= cap,
        ...(deleted === undefined ? {} : { deleted }),
        keptEdited: kept,
      };
    }
    // Operator-facing diagnostic only — the 502 body stays a fixed opaque
    // string carrying no raw subprocess output and NO created-count (spec:
    // events inserted before the failure persist and are reported nowhere in
    // the error body). Regenerate: the snapshot is NOT deleted here — the
    // prior auto rows persist alongside any partial new rows the failed run
    // inserted, exactly like the existing append-failure semantics.
    console.warn(
      `[events/generate] session=${sessionId}: generation failed — AI turn failed (${outcome.detail})` +
        sdkFailureSuffix(outcome.failure, outcome.ending, outcome.summary) +
        sdkFallbackSuffix(outcome),
    );
    // batch-autogenerate D7: a failed batch run deletes the events of every attempt, this one
    // included, so the session is left "missing" for a later job.
    const kept = batch ? (await deleteOwnEvents(p, sessionId, [...earlier, runId])).keptEdited : 0;
    return {
      kind: 'failed',
      rateLimited:
        outcome.failure?.kind === 'provider' && isRateLimitStatus(outcome.failure.status),
      providerFailed: isProviderRefusal(outcome.failure),
      keptEdited: kept,
    };
  } finally {
    // Slot release, unconditionally (Phase-4 review): a leaked slot wedges every later AI turn
    // for this session behind a 409 until restart. The catalog projection needs no post-run
    // write: each insert and the regenerate's delete commit it in their own transaction
    // (session-tables design D8), so it is current by the time the route responds.
    // Lease, then slot, before the response (session-run-leases D4).
    await slot.release();
  }
}
