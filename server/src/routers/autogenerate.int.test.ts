describe('POST …/autogenerate-jobs (start)', () => {
  it('422 without expected_sessions; 503s; 403; 201; live 409; expected 409', async () => {
    const t = await team(2);
    const noExpected = await req('POST', base(t), t.admin.cookie, scope(t));
    expect(noExpected.status).toBe(422);
    expect(
      (
        await req(
          'POST',
          base(t),
          t.admin.cookie,
          { ...scope(t), expected_sessions: 2 },
          envWith({ HOST: '127.0.0.1' }),
        )
      ).json,
    ).toEqual({ detail: STT_503 });
    const bare = await user(t.team, 'admin');
    expect(
      (await req('POST', base(t), bare.cookie, { ...scope(t, ['topics']), expected_sessions: 2 }))
        .json,
    ).toEqual({ detail: LLM_503 });
    const unapproved = await user(t.team, 'admin', NOT_APPROVED_EMAIL);
    const forbidden = await req('POST', base(t), unapproved.cookie, {
      ...scope(t, ['transcript']),
      expected_sessions: 2,
    });
    expect([forbidden.status, forbidden.json]).toEqual([403, { detail: RUN_403 }]);
    const changed = await req('POST', base(t), t.admin.cookie, {
      ...scope(t),
      expected_sessions: 3,
    });
    expect([changed.status, changed.json]).toEqual([
      409,
      { detail: 'The sessions changed since the estimate.', sessions: 2 },
    ]);
    const created = await req('POST', base(t), t.admin.cookie, {
      ...scope(t),
      expected_sessions: 2,
    });
    expect(created.status).toBe(201);
    const job = (created.json as { job: Record<string, unknown> }).job;
    expect(job).toMatchObject({
      team_id: t.team,
      status: 'queued',
      stop_reason: null,
      scope: 'shows',
      show_ids: [t.show],
      steps: ['transcript', 'topics'],
      wiki_mode: 'accept',
      initiator_id: t.admin.id,
      sessions: 2,
      counts: { pending: 4, running: 0, done: 0, skipped: 0, failed: 0, cancelled: 0 },
      current: null,
      cancel_requested_by_name: null,
    });
    expect(created.res.headers.get('set-cookie')).toBeNull();
    const second = await req('POST', base(t), t.owner.cookie, {
      ...scope(t),
      expected_sessions: 2,
    });
    expect([second.status, second.json]).toEqual([
      409,
      { detail: 'A batch job is already running for this team.', job_id: job.id },
    ]);
    // No credential in the rows.
    const row = await testDb().first<Record<string, unknown>>(
      'SELECT * FROM autogenerate_jobs WHERE id = ?',
      job.id,
    );
    expect(JSON.stringify(row)).not.toMatch(/sk-|key|token/i);
  });

  it('two concurrent starts give one 201 and one 409', async () => {
    const t = await team(2);
    const [a, b] = await Promise.all([
      req('POST', base(t), t.admin.cookie, { ...scope(t), expected_sessions: 2 }),
      req('POST', base(t), t.owner.cookie, { ...scope(t), expected_sessions: 2 }),
    ]);
    expect([a.status, b.status].sort()).toEqual([201, 409]);
  });
});

describe('list, detail, cancel', () => {
  async function started(t: Team) {
    const r = await req('POST', base(t), t.admin.cookie, {
      ...scope(t),
      expected_sessions: t.sessions.length,
    });
    return (r.json as { job: { id: string } }).job.id;
  }

  it('lists newest first; details items in order with the contract’s pairs; 404 for another team’s job', async () => {
    const t = await team(2);
    const id = await started(t);
    await testDb().run(
      `UPDATE autogenerate_items SET status = 'skipped', outcome = 'present', finished_at_ms = 1,
         kept_edited = 0 WHERE job_id = ? AND step = 'topics'`,
      id,
    );
    const list = await req('GET', base(t), t.owner.cookie);
    expect((list.json.jobs as Array<{ id: string }>).map((j) => j.id)).toEqual([id]);
    const d = await req('GET', `${base(t)}/${id}`, t.owner.cookie);
    expect(d.status).toBe(200);
    const body = autogenerateDetailResponseSchema.parse(d.json);
    expect(body.sessions.map((s) => s.ordinal)).toEqual([0, 1]);
    for (const s of body.sessions) {
      expect(s.steps.map((x) => x.step)).toEqual(['transcript', 'topics']);
      expect(s.steps[1]).toMatchObject({
        status: 'skipped',
        outcome: 'present',
        detail: AUTOGENERATE_OUTCOMES.present.detail,
        kept_edited: 0,
        wiki_accepted: null,
      });
      expect(s.steps[0]).toMatchObject({
        status: 'pending',
        outcome: null,
        detail: null,
        kept_edited: null,
      });
    }
    const other = await team(1);
    const foreign = await req('GET', `${base(other)}/${id}`, other.admin.cookie);
    expect([foreign.status, foreign.json]).toEqual([404, { detail: 'Job not found.' }]);
  });

  it('cancel: queued becomes cancelled; running records it; a repeat is 200; an ended job 409', async () => {
    const t = await team(1);
    const id = await started(t);
    const c1 = await req('POST', `${base(t)}/${id}/cancel`, t.owner.cookie);
    expect(c1.status).toBe(200);
    expect((c1.json as { job: Record<string, unknown> }).job).toMatchObject({
      status: 'cancelled',
      stop_reason: 'cancelled',
    });
    const again = await req('POST', `${base(t)}/${id}/cancel`, t.owner.cookie);
    expect([again.status, again.json]).toEqual([
      409,
      { detail: 'Job already ended.', status: 'cancelled' },
    ]);

    const id2 = await started(t);
    await testDb().run(
      `UPDATE autogenerate_jobs SET status = 'running', locked_by = 'w', locked_until_ms = 9 WHERE id = ?`,
      id2,
    );
    const r1 = await req('POST', `${base(t)}/${id2}/cancel`, t.admin.cookie, { ignored: true });
    expect((r1.json as { job: Record<string, unknown> }).job).toMatchObject({ status: 'running' });
    expect(
      (r1.json as { job: { cancel_requested_by_name: string } }).job.cancel_requested_by_name,
    ).toBeTruthy();
    const r2 = await req('POST', `${base(t)}/${id2}/cancel`, t.owner.cookie);
    expect(r2.status).toBe(200);
    await testDb().run(
      `UPDATE autogenerate_jobs SET status = 'finished', finished_at_ms = 1 WHERE id = ?`,
      id2,
    );
    expect((await req('POST', `${base(t)}/${id2}/cancel`, t.owner.cookie)).json).toEqual({
      detail: 'Job already ended.',
      status: 'finished',
    });
    expect((await req('POST', `${base(t)}/missing/cancel`, t.owner.cookie)).json).toEqual({
      detail: 'Job not found.',
    });
  });
});

