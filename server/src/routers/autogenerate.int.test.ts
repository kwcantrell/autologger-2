interface Team {
  team: string;
  show: string;
  sessions: string[];
  owner: { id: string; cookie: string };
  admin: { id: string; cookie: string };
  member: { id: string; cookie: string };
  outsider: { id: string; cookie: string };
}

async function user(team: string | null, role: 'owner' | 'admin' | 'member', email?: string) {
  const id = await seedUser({ email });
  if (team) await catalogFor().auth.authAddMembershipWithRole(id, team, role);
  return { id, cookie: await loginCookie(id) };
}

/** A team with one show of `n` sessions; owner and admin hold AI SDK routes. */
async function team(n = 3): Promise<Team> {
  const t = await seedStudio();
  const show = await seedShow({ studioId: t, categoriesJson: GEN_CATEGORIES_JSON });
  const sessions: string[] = [];
  for (let i = 0; i < n; i++) sessions.push(await seedSession({ showId: show }));
  const owner = await user(t, 'owner');
  const admin = await user(t, 'admin');
  const member = await user(t, 'member');
  await catalogFor().auth.authGrantShow(member.id, show, owner.id, new Date().toISOString());
  const outsider = await user(null, 'member');
  const llm = await fakeProvider(() => ({ status: 500, body: '{}' }));
  for (const u of [owner, admin]) await saveSdkCredential(llm.baseURL, { cookie: u.cookie });
  return { team: t, show, sessions, owner, admin, member, outsider };
}

