type Issue = { code: string; path: (string | number)[]; message: string };
function issuesOf(r: { success: boolean; error?: { issues: unknown[] } }): Issue[] {
  expect(r.success).toBe(false);
  const issues = (r.error?.issues ?? []) as Issue[];
  expect(issues.length).toBeGreaterThan(0);
  for (const i of issues) {
    expect(typeof i.code).toBe('string');
    expect(Array.isArray(i.path)).toBe(true);
    expect(typeof i.message).toBe('string');
  }
  return issues;
}
const ids = (n: number) => Array.from({ length: n }, (_, i) => `id${i}`);

describe('the scope body', () => {
  it('takes exactly one of show_ids and session_ids, and defaults wiki_mode to accept', () => {
    expect(autogenerateScopeBodySchema.parse({ show_ids: ['s1'], steps: ['wiki'] })).toEqual({
      show_ids: ['s1'],
      steps: ['wiki'],
      wiki_mode: 'accept',
    });
    expect(
      autogenerateScopeBodySchema.parse({
        session_ids: ['a', 'b'],
        steps: ['topics', 'transcript'],
        wiki_mode: 'pending',
      }),
    ).toEqual({ session_ids: ['a', 'b'], steps: ['topics', 'transcript'], wiki_mode: 'pending' });
  });

  it('refuses both scopes, neither, and an empty list, each with zod 4 issues', () => {
    issuesOf(
      autogenerateScopeBodySchema.safeParse({
        show_ids: ['s'],
        session_ids: ['x'],
        steps: ['wiki'],
      }),
    );
    issuesOf(autogenerateScopeBodySchema.safeParse({ steps: ['wiki'] }));
    issuesOf(autogenerateScopeBodySchema.safeParse({ show_ids: [], steps: ['wiki'] }));
    issuesOf(autogenerateScopeBodySchema.safeParse({ session_ids: [], steps: ['wiki'] }));
    issuesOf(autogenerateScopeBodySchema.safeParse({ show_ids: [''], steps: ['wiki'] }));
  });

  it('caps show_ids at 200 and session_ids at 1000', () => {
    expect(
      autogenerateScopeBodySchema.safeParse({ show_ids: ids(200), steps: ['wiki'] }).success,
    ).toBe(true);
    issuesOf(autogenerateScopeBodySchema.safeParse({ show_ids: ids(201), steps: ['wiki'] }));
    expect(
      autogenerateScopeBodySchema.safeParse({ session_ids: ids(1000), steps: ['wiki'] }).success,
    ).toBe(true);
    issuesOf(autogenerateScopeBodySchema.safeParse({ session_ids: ids(1001), steps: ['wiki'] }));
  });

  it('requires non-empty unique steps from the four, and a known wiki mode', () => {
    issuesOf(autogenerateScopeBodySchema.safeParse({ show_ids: ['s'], steps: [] }));
    issuesOf(autogenerateScopeBodySchema.safeParse({ show_ids: ['s'] }));
    issuesOf(autogenerateScopeBodySchema.safeParse({ show_ids: ['s'], steps: ['wiki', 'wiki'] }));
    issuesOf(autogenerateScopeBodySchema.safeParse({ show_ids: ['s'], steps: ['summary'] }));
    issuesOf(
      autogenerateScopeBodySchema.safeParse({ show_ids: ['s'], steps: ['wiki'], wiki_mode: 'x' }),
    );
  });
});

describe('the start body', () => {
  it('requires a non-negative integer expected_sessions', () => {
    const base = { show_ids: ['s'], steps: ['wiki'] };
    expect(autogenerateStartBodySchema.parse({ ...base, expected_sessions: 12 })).toMatchObject({
      expected_sessions: 12,
      wiki_mode: 'accept',
    });
    expect(autogenerateStartBodySchema.safeParse({ ...base, expected_sessions: 0 }).success).toBe(
      true,
    );
    const missing = issuesOf(autogenerateStartBodySchema.safeParse(base));
    expect(missing.some((i) => i.path.join('.') === 'expected_sessions')).toBe(true);
    issuesOf(autogenerateStartBodySchema.safeParse({ ...base, expected_sessions: -1 }));
    issuesOf(autogenerateStartBodySchema.safeParse({ ...base, expected_sessions: 1.5 }));
    issuesOf(autogenerateStartBodySchema.safeParse({ ...base, expected_sessions: '12' }));
  });
});

