// Batch autogenerate jobs and items (OpenSpec change `batch-autogenerate`, design D1-D3, D7, D13,
// D14), in `catalog.autogenerate_jobs` and `catalog.autogenerate_items` (migration 20261025000000).
//
// One store, two kinds of caller:
// - **as the signed-in manager** (the routes, and `startAutogenerateJob`): the scope's candidates,
//   the preview's missing counts, the job's creation (job, items and order in one transaction, so
//   row-level security proves the caller manages the team at commit time), the list, the detail
//   and the cancel request. Rows of a team the caller does not manage read as missing.
// - **as the worker** (`autogenerateWorkerCatalog`, the reviewed system reason
//   `autogenerate-worker`): the claim, the lease renewal, the item and job transitions, the
//   write-ahead of run ids and topic ids, and the recorded partial output of a session and step.
//   Every worker write is fenced on the job's lease (`locked_by = <worker>` and
//   `status = 'running'`) and reports the rows it changed, so a worker that lost its lease writes
//   nothing (design D3, D7 "Fenced write-ahead").
//
// No column can hold a credential or provider text: outcomes and stop reasons are fixed codes
// (check-constrained), and their details are looked up in `@autologger/contract`.

import type { CatalogDb } from '@autologger/ports';
import type { CatalogFacade } from './catalog';

export type AutogenerateStepName = 'transcript' | 'events' | 'topics' | 'wiki';
export const AUTOGENERATE_STEP_ORDER: readonly AutogenerateStepName[] = [
  'transcript',
  'events',
  'topics',
  'wiki',
];

/** A job row as stored (times in Clock epoch milliseconds). */
export interface AutogenerateJobRow {
  id: string;
  team_id: string;
  initiator_user_id: string;
  initiator_name: string;
  scope: 'shows' | 'sessions';
  show_ids: string[] | null;
  steps: AutogenerateStepName[];
  wiki_mode: 'accept' | 'pending';
  status: 'queued' | 'running' | 'finished' | 'cancelled' | 'failed';
  stop_reason: string | null;
  consecutive_stt_failures: number;
  consecutive_llm_failures: number;
  session_count: number;
  locked_by: string | null;
  locked_until_ms: number | null;
  cancel_requested_at_ms: number | null;
  cancel_requested_by_user_id: string | null;
  cancel_requested_by_name: string | null;
  created_at_ms: number;
  started_at_ms: number | null;
  finished_at_ms: number | null;
  updated_at_ms: number;
}

export type AutogenerateItemStatus =
  | 'pending'
  | 'running'
  | 'done'
  | 'skipped'
  | 'failed'
  | 'cancelled';

/** An item row as stored. `run_ids` and `own_topic_ids` are the comma lists split. */
export interface AutogenerateItemRow {
  job_id: string;
  session_id: string;
  step: AutogenerateStepName;
  ordinal: number;
  step_order: number;
  effective_date: string | null;
  status: AutogenerateItemStatus;
  outcome: string | null;
  attempts: number;
  run_ids: string[];
  own_topic_ids: string[];
  kept_edited: number | null;
  wiki_accepted: number | null;
  wiki_pending: number | null;
  started_at_ms: number | null;
  finished_at_ms: number | null;
}

/** Item counts by status, and the running item, for the job object. */
export interface AutogenerateJobSummary extends AutogenerateJobRow {
  counts: Record<AutogenerateItemStatus, number>;
  current: { session_id: string; step: AutogenerateStepName } | null;
}

/** One candidate session of a scope, in processing order. */
export interface AutogenerateCandidate {
  id: string;
  show_id: string;
  effective_date: string | null;
}

export type AutogenerateScope = { showIds: string[] } | { sessionIds: string[] };

export type AutogenerateScopeResult =
  | { ok: true; sessions: AutogenerateCandidate[] }
  | { ok: false; reason: 'show-not-found' | 'session-not-found' };

export interface AutogenerateCreateInput {
  teamId: string;
  initiatorId: string;
  initiatorName: string;
  scope: AutogenerateScope;
  steps: AutogenerateStepName[];
  wikiMode: 'accept' | 'pending';
  expectedSessions: number;
  nowMs: number;
}

export type AutogenerateCreateResult =
  | { kind: 'created'; job: AutogenerateJobSummary }
  | { kind: 'show-not-found' }
  | { kind: 'session-not-found' }
  | { kind: 'no-sessions' }
  | { kind: 'too-many' }
  | { kind: 'live-job'; jobId: string }
  | { kind: 'sessions-changed'; sessions: number };

export interface AutogenerateDetailItem extends AutogenerateItemRow {
  title: string;
  show_id: string;
}

export type AutogenerateCancelResult =
  | { kind: 'not-found' }
  | { kind: 'ended'; status: AutogenerateJobRow['status'] }
  | { kind: 'ok'; job: AutogenerateJobSummary };

