/** The worker's catalog: the reviewed system reason `autogenerate-worker` (core-ports-architecture
 * "Every catalog and session call is bound to a caller"): the claim, lease, item and job writes and
 * the initiator re-read. The session work runs as the initiator, never through this binding. */
export function autogenerateWorkerCatalog(catalog: CatalogFacade): CatalogFacade {
  return catalog.system('autogenerate-worker');
}

const num = (v: unknown): number => Number(v);
const numOrNull = (v: unknown): number | null => (v === null || v === undefined ? null : Number(v));
const list = (v: unknown): string[] => (typeof v === 'string' && v !== '' ? v.split(',') : []);

function jobFromRow(r: Record<string, unknown>): AutogenerateJobRow {
  return {
    id: String(r.id),
    team_id: String(r.team_id),
    initiator_user_id: String(r.initiator_user_id),
    initiator_name: String(r.initiator_name),
    scope: r.scope as AutogenerateJobRow['scope'],
    show_ids: r.show_ids_json === null ? null : (JSON.parse(String(r.show_ids_json)) as string[]),
    steps: String(r.steps).split(',') as AutogenerateStepName[],
    wiki_mode: r.wiki_mode as AutogenerateJobRow['wiki_mode'],
    status: r.status as AutogenerateJobRow['status'],
    stop_reason: (r.stop_reason as string | null) ?? null,
    consecutive_stt_failures: num(r.consecutive_stt_failures),
    consecutive_llm_failures: num(r.consecutive_llm_failures),
    session_count: num(r.session_count),
    locked_by: (r.locked_by as string | null) ?? null,
    locked_until_ms: numOrNull(r.locked_until_ms),
    cancel_requested_at_ms: numOrNull(r.cancel_requested_at_ms),
    cancel_requested_by_user_id: (r.cancel_requested_by_user_id as string | null) ?? null,
    cancel_requested_by_name: (r.cancel_requested_by_name as string | null) ?? null,
    created_at_ms: num(r.created_at_ms),
    started_at_ms: numOrNull(r.started_at_ms),
    finished_at_ms: numOrNull(r.finished_at_ms),
    updated_at_ms: num(r.updated_at_ms),
  };
}

function itemFromRow(r: Record<string, unknown>): AutogenerateItemRow {
  return {
    job_id: String(r.job_id),
    session_id: String(r.session_id),
    step: r.step as AutogenerateStepName,
    ordinal: num(r.ordinal),
    step_order: num(r.step_order),
    effective_date: (r.effective_date as string | null) ?? null,
    status: r.status as AutogenerateItemStatus,
    outcome: (r.outcome as string | null) ?? null,
    attempts: num(r.attempts),
    run_ids: list(r.run_ids),
    own_topic_ids: list(r.own_topic_ids),
    kept_edited: numOrNull(r.kept_edited),
    wiki_accepted: numOrNull(r.wiki_accepted),
    wiki_pending: numOrNull(r.wiki_pending),
    started_at_ms: numOrNull(r.started_at_ms),
    finished_at_ms: numOrNull(r.finished_at_ms),
  };
}

/** The job row with its item counts and running item (the job object's `counts` and `current`). */
const SUMMARY_SELECT = `SELECT j.*,
    c.pending, c.running, c.done, c.skipped, c.failed, c.cancelled,
    cur.session_id AS current_session_id, cur.step AS current_step
  FROM autogenerate_jobs j
  LEFT JOIN LATERAL (
    SELECT count(*) FILTER (WHERE i.status = 'pending')::int AS pending,
           count(*) FILTER (WHERE i.status = 'running')::int AS running,
           count(*) FILTER (WHERE i.status = 'done')::int AS done,
           count(*) FILTER (WHERE i.status = 'skipped')::int AS skipped,
           count(*) FILTER (WHERE i.status = 'failed')::int AS failed,
           count(*) FILTER (WHERE i.status = 'cancelled')::int AS cancelled
    FROM autogenerate_items i WHERE i.job_id = j.id) c ON true
  LEFT JOIN LATERAL (
    SELECT i.session_id, i.step FROM autogenerate_items i
    WHERE i.job_id = j.id AND i.status = 'running'
    ORDER BY i.ordinal, i.step_order LIMIT 1) cur ON true`;

function summaryFromRow(r: Record<string, unknown>): AutogenerateJobSummary {
  return {
    ...jobFromRow(r),
    counts: {
      pending: num(r.pending ?? 0),
      running: num(r.running ?? 0),
      done: num(r.done ?? 0),
      skipped: num(r.skipped ?? 0),
      failed: num(r.failed ?? 0),
      cancelled: num(r.cancelled ?? 0),
    },
    current:
      r.current_session_id === null || r.current_session_id === undefined
        ? null
        : {
            session_id: String(r.current_session_id),
            step: r.current_step as AutogenerateStepName,
          },
  };
}

/** Design D13: `episode_date` when it is `YYYY-MM-DD`, else the first ten characters of
 * `started_at_utc`, else those of `created_at_utc`, each only when they form such a date. */
const EFFECTIVE_DATE = `CASE
    WHEN s.episode_date ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' THEN s.episode_date
    WHEN left(s.started_at_utc, 10) ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' THEN left(s.started_at_utc, 10)
    WHEN left(s.created_at_utc, 10) ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' THEN left(s.created_at_utc, 10)
  END`;
const CANDIDATE_ORDER = `ORDER BY effective_date NULLS LAST, s.started_at_utc, s.created_at_utc, s.id`;

/** The lease fence of every worker write (design D3). */
const FENCE = `EXISTS (SELECT 1 FROM autogenerate_jobs j
  WHERE j.id = ? AND j.locked_by = ? AND j.status = 'running')`;

function isUniqueViolation(e: unknown): boolean {
  for (let x: unknown = e, i = 0; x && i < 3; i++) {
    if ((x as { code?: unknown }).code === '23505') return true;
    x = (x as { cause?: unknown }).cause;
  }
  return false;
}

export class AutogenerateStore implements AutogenerateStoreFacade {
  constructor(private readonly db: CatalogDb) {}

  /** The scope's candidate sessions in processing order (design D13), under the caller's
   * binding. A show id that is not a show of the team, or a session id that is not an accessible,
   * non-deleted session of a show of the team, refuses the whole scope. */
  async resolveScope(teamId: string, scope: AutogenerateScope): Promise<AutogenerateScopeResult> {
    return resolveScopeOn(this.db, teamId, scope);
  }

  /** The candidates whose transcript, auto-generated events and topics are missing now (the
   * preview's estimate; design D14), under the caller's binding. */
  async previewMissing(
    sessionIds: string[],
  ): Promise<{ transcript: number; events: number; topics: number }> {
    if (sessionIds.length === 0) return { transcript: 0, events: 0, topics: 0 };
    const row = await this.db.first<Record<string, unknown>>(
      `WITH c AS (SELECT DISTINCT v AS id FROM json_array_elements_text(?::text::json) v)
       SELECT
         count(*) FILTER (WHERE NOT EXISTS (
           SELECT 1 FROM session_transcript_words w WHERE w.session_id = c.id))::int AS transcript,
         count(*) FILTER (WHERE NOT EXISTS (
           SELECT 1 FROM session_events e WHERE e.session_id = c.id
             AND coalesce(CASE WHEN pg_input_is_valid(e.metadata_json, 'jsonb')
               THEN (e.metadata_json::jsonb -> 'auto_generated') = 'true'::jsonb END, false)))::int
           AS events,
         count(*) FILTER (WHERE NOT EXISTS (
           SELECT 1 FROM session_topics t WHERE t.session_id = c.id))::int AS topics
       FROM c`,
      JSON.stringify(sessionIds),
    );
    return {
      transcript: num(row?.transcript ?? 0),
      events: num(row?.events ?? 0),
      topics: num(row?.topics ?? 0),
    };
  }

  /** The team's `queued` or `running` job, if any (visible to its managers). */
  async liveJobId(teamId: string): Promise<string | null> {
    const row = await this.db.first<{ id: string }>(
      `SELECT id FROM autogenerate_jobs WHERE team_id = ? AND status IN ('queued', 'running')`,
      teamId,
    );
    return row?.id ?? null;
  }

  /** Creates the job, its items and their order in one transaction under the caller's binding
   * (design D2, D14): the scope is resolved again inside it, and the live index makes a concurrent
   * second start a `live-job`. */
  async createJob(input: AutogenerateCreateInput): Promise<AutogenerateCreateResult> {
    const id = crypto.randomUUID();
    let result: AutogenerateCreateResult;
    try {
      result = await this.db.tx(async (t) => {
        const scope = await resolveScopeOn(t, input.teamId, input.scope);
        if (!scope.ok) return { kind: scope.reason };
        const n = scope.sessions.length;
        if (n === 0) return { kind: 'no-sessions' };
        if (n > AUTOGENERATE_SESSION_CAP) return { kind: 'too-many' };
        const live = await t.first<{ id: string }>(
          `SELECT id FROM autogenerate_jobs WHERE team_id = ? AND status IN ('queued', 'running')`,
          input.teamId,
        );
        if (live) return { kind: 'live-job', jobId: live.id };
        if (n !== input.expectedSessions) return { kind: 'sessions-changed', sessions: n };
        const steps = AUTOGENERATE_STEP_ORDER.filter((s) => input.steps.includes(s));
        await t.run(
          `INSERT INTO autogenerate_jobs (id, team_id, initiator_user_id, initiator_name, scope,
             show_ids_json, steps, wiki_mode, status, session_count, created_at_ms, updated_at_ms)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?, 'queued', ?, ?, ?)`,
          id,
          input.teamId,
          input.initiatorId,
          input.initiatorName,
          'showIds' in input.scope ? 'shows' : 'sessions',
          'showIds' in input.scope ? JSON.stringify([...new Set(input.scope.showIds)]) : null,
          steps.join(','),
          input.wikiMode,
          n,
          input.nowMs,
          input.nowMs,
        );
        // One statement for every item: the candidates in order × the selected steps.
        await t.run(
          `INSERT INTO autogenerate_items (job_id, session_id, step, ordinal, step_order,
             effective_date)
           SELECT ?, c.id, s.step, (c.o - 1)::int, s.step_order::smallint, c.effective_date
           FROM json_to_recordset(?::text::json) AS c(id text, effective_date text, o int)
           CROSS JOIN json_to_recordset(?::text::json) AS s(step text, step_order int)`,
          id,
          JSON.stringify(
            scope.sessions.map((c, i) => ({
              id: c.id,
              effective_date: c.effective_date,
              o: i + 1,
            })),
          ),
          JSON.stringify(
            steps.map((step) => ({ step, step_order: AUTOGENERATE_STEP_ORDER.indexOf(step) })),
          ),
        );
        return { kind: 'created', job: null as unknown as AutogenerateJobSummary };
      });
    } catch (e) {
      if (!isUniqueViolation(e)) throw e;
      const live = await this.liveJobId(input.teamId);
      if (live) return { kind: 'live-job', jobId: live };
      throw e;
    }
    if (result.kind !== 'created') return result;
    const job = await this.getJob(input.teamId, id);
    if (!job) throw new Error('autogenerate job vanished after create');
    return { kind: 'created', job };
  }

  /** The team's newest jobs, newest first. */
  async listJobs(teamId: string): Promise<AutogenerateJobSummary[]> {
    const rows = await this.db.all<Record<string, unknown>>(
      `${SUMMARY_SELECT} WHERE j.team_id = ? ORDER BY j.created_at_ms DESC, j.id DESC LIMIT ?`,
      teamId,
      AUTOGENERATE_LIST_LIMIT,
    );
    return rows.map(summaryFromRow);
  }

  /** One job of the team, or null (another team's, or missing). */
  async getJob(teamId: string, jobId: string): Promise<AutogenerateJobSummary | null> {
    const row = await this.db.first<Record<string, unknown>>(
      `${SUMMARY_SELECT} WHERE j.team_id = ? AND j.id = ?`,
      teamId,
      jobId,
    );
    return row ? summaryFromRow(row) : null;
  }

  /** The job's items in processing order with each session's current title and show (`""` when
   * the session no longer exists or is no longer visible). */
  async detailItems(jobId: string): Promise<AutogenerateDetailItem[]> {
    const rows = await this.db.all<Record<string, unknown>>(
      `SELECT i.*, coalesce(s.title, '') AS session_title, coalesce(s.show_id, '') AS session_show
       FROM autogenerate_items i LEFT JOIN sessions s ON s.id = i.session_id
       WHERE i.job_id = ? ORDER BY i.ordinal, i.step_order`,
      jobId,
    );
    return rows.map((r) => ({
      ...itemFromRow(r),
      title: String(r.session_title ?? ''),
      show_id: String(r.session_show ?? ''),
    }));
  }

  /** Records a cancel as the caller (design D2, D10): a `queued` job ends `cancelled` at once; a
   * `running` job keeps running until its current step ends. A repeat on a live job changes
   * nothing and answers the job. */
  async requestCancel(
    teamId: string,
    jobId: string,
    by: { id: string; name: string },
    nowMs: number,
  ): Promise<AutogenerateCancelResult> {
    const before = await this.getJob(teamId, jobId);
    if (!before) return { kind: 'not-found' };
    if (before.status !== 'queued' && before.status !== 'running') {
      return { kind: 'ended', status: before.status };
    }
    if (before.cancel_requested_at_ms === null) {
      await this.db.run(
        `UPDATE autogenerate_jobs SET
           cancel_requested_at_ms = ?, cancel_requested_by_user_id = ?,
           cancel_requested_by_name = ?, updated_at_ms = ?,
           status = CASE WHEN status = 'queued' THEN 'cancelled' ELSE status END,
           stop_reason = CASE WHEN status = 'queued' THEN 'cancelled' ELSE stop_reason END,
           finished_at_ms = CASE WHEN status = 'queued' THEN ? ELSE finished_at_ms END
         WHERE id = ? AND team_id = ? AND status IN ('queued', 'running')
           AND cancel_requested_at_ms IS NULL`,
        nowMs,
        by.id,
        by.name,
        nowMs,
        nowMs,
        jobId,
        teamId,
      );
    }
    const after = await this.getJob(teamId, jobId);
    if (!after) return { kind: 'not-found' };
    // Live, or the queued job this request (or a concurrent one) just cancelled; anything else
    // ended on its own in between.
    const cancelledNow =
      before.status === 'queued' &&
      after.status === 'cancelled' &&
      after.cancel_requested_at_ms !== null;
    if (after.status === 'queued' || after.status === 'running' || cancelledNow) {
      return { kind: 'ok', job: after };
    }
    return { kind: 'ended', status: after.status };
  }

  // -- the worker (system binding `autogenerate-worker`) ---------------------------------------

  /** Claims the oldest due job: `queued`, or `running` with a lapsed lease (design D3). */
  async claim(
    workerId: string,
    nowMs: number,
    leaseMs: number,
  ): Promise<AutogenerateJobRow | null> {
    const row = await this.db.first<Record<string, unknown>>(
      `UPDATE autogenerate_jobs SET status = 'running', locked_by = ?, locked_until_ms = ?,
         started_at_ms = coalesce(started_at_ms, ?), updated_at_ms = ?
       WHERE id = (SELECT id FROM autogenerate_jobs
                   WHERE status = 'queued'
                      OR (status = 'running' AND (locked_until_ms IS NULL OR locked_until_ms < ?))
                   ORDER BY created_at_ms, id
                   FOR UPDATE SKIP LOCKED LIMIT 1)
       RETURNING *`,
      workerId,
      nowMs + leaseMs,
      nowMs,
      nowMs,
      nowMs,
    );
    return row ? jobFromRow(row) : null;
  }

  /** Renews the lease: `lost` when another worker holds the job or it ended, `gone` when the row
   * no longer exists (its team was deleted). */
  async renew(
    jobId: string,
    workerId: string,
    nowMs: number,
    leaseMs: number,
  ): Promise<'ok' | 'lost' | 'gone'> {
    const r = await this.db.run(
      `UPDATE autogenerate_jobs SET locked_until_ms = ?, updated_at_ms = ?
       WHERE id = ? AND locked_by = ? AND status = 'running'`,
      nowMs + leaseMs,
      nowMs,
      jobId,
      workerId,
    );
    if (r.changes > 0) return 'ok';
    const exists = await this.db.first('SELECT 1 AS x FROM autogenerate_jobs WHERE id = ?', jobId);
    return exists ? 'lost' : 'gone';
  }

  /** A clean shutdown lets the lease lapse at once, so another process resumes without waiting. */
  async release(jobId: string, workerId: string): Promise<number> {
    const r = await this.db.run(
      `UPDATE autogenerate_jobs SET locked_until_ms = 0
       WHERE id = ? AND locked_by = ? AND status = 'running'`,
      jobId,
      workerId,
    );
    return r.changes;
  }

  async readJob(jobId: string): Promise<AutogenerateJobRow | null> {
    const row = await this.db.first<Record<string, unknown>>(
      'SELECT * FROM autogenerate_jobs WHERE id = ?',
      jobId,
    );
    return row ? jobFromRow(row) : null;
  }

  async items(jobId: string): Promise<AutogenerateItemRow[]> {
    const rows = await this.db.all<Record<string, unknown>>(
      'SELECT * FROM autogenerate_items WHERE job_id = ? ORDER BY ordinal, step_order',
      jobId,
    );
    return rows.map(itemFromRow);
  }

  async updateItem(
    jobId: string,
    workerId: string,
    sessionId: string,
    step: AutogenerateStepName,
    patch: AutogenerateItemPatch,
  ): Promise<number> {
    const cols = Object.keys(patch) as (keyof AutogenerateItemPatch)[];
    if (cols.length === 0) return 0;
    const allowed = new Set([
      'status',
      'outcome',
      'attempts',
      'kept_edited',
      'wiki_accepted',
      'wiki_pending',
      'started_at_ms',
      'finished_at_ms',
    ]);
    for (const c of cols) if (!allowed.has(c)) throw new TypeError(`not an item field: ${c}`);
    const r = await this.db.run(
      `UPDATE autogenerate_items SET ${cols.map((c) => `${c} = ?`).join(', ')}
       WHERE job_id = ? AND session_id = ? AND step = ? AND ${FENCE}`,
      ...cols.map((c) => patch[c] ?? null),
      jobId,
      sessionId,
      step,
      jobId,
      workerId,
    );
    return r.changes;
  }

  /** Write-ahead of an events or wiki run id (design D7), fenced on the lease: 0 means the lease
   * is lost and the run must not start. */
  async appendRunId(
    jobId: string,
    workerId: string,
    sessionId: string,
    step: AutogenerateStepName,
    runId: string,
  ): Promise<number> {
    return this.#append('run_ids', jobId, workerId, sessionId, step, runId);
  }

  /** Write-ahead of a topic id, before the topic is inserted (design D7), fenced on the lease. */
  async appendTopicId(
    jobId: string,
    workerId: string,
    sessionId: string,
    step: AutogenerateStepName,
    topicId: string,
  ): Promise<number> {
    return this.#append('own_topic_ids', jobId, workerId, sessionId, step, topicId);
  }

  async #append(
    col: 'run_ids' | 'own_topic_ids',
    jobId: string,
    workerId: string,
    sessionId: string,
    step: AutogenerateStepName,
    value: string,
  ): Promise<number> {
    if (value.includes(',') || value === '') throw new TypeError('not a recordable id');
    const r = await this.db.run(
      `UPDATE autogenerate_items
       SET ${col} = CASE WHEN ${col} = '' THEN ? ELSE ${col} || ',' || ? END
       WHERE job_id = ? AND session_id = ? AND step = ? AND ${FENCE}`,
      value,
      value,
      jobId,
      sessionId,
      step,
      jobId,
      workerId,
    );
    return r.changes;
  }

  /** Every run id and topic id recorded on an item of any job, for this session and step, whose
   * status is not `done` (design D7 "Recorded partial output, across jobs"). */
  async recordedPartialOutput(
    sessionId: string,
    step: AutogenerateStepName,
  ): Promise<{ runIds: string[]; topicIds: string[] }> {
    const rows = await this.db.all<{ run_ids: string; own_topic_ids: string }>(
      `SELECT run_ids, own_topic_ids FROM autogenerate_items
       WHERE session_id = ? AND step = ? AND status <> 'done'`,
      sessionId,
      step,
    );
    const runIds = new Set<string>();
    const topicIds = new Set<string>();
    for (const r of rows) {
      for (const x of list(r.run_ids)) runIds.add(x);
      for (const x of list(r.own_topic_ids)) topicIds.add(x);
    }
    return { runIds: [...runIds], topicIds: [...topicIds] };
  }

  /** Ends every item not yet ended with `cancelled`/`outcome` (a cancel or a job stop). */
  async cancelRemaining(
    jobId: string,
    workerId: string,
    outcome: 'cancelled' | 'job-stopped',
    nowMs: number,
  ): Promise<number> {
    const r = await this.db.run(
      `UPDATE autogenerate_items SET status = 'cancelled', outcome = ?, finished_at_ms = ?
       WHERE job_id = ? AND status IN ('pending', 'running') AND ${FENCE}`,
      outcome,
      nowMs,
      jobId,
      jobId,
      workerId,
    );
    return r.changes;
  }

  async setFailureCounts(
    jobId: string,
    workerId: string,
    stt: number,
    llm: number,
    nowMs: number,
  ): Promise<number> {
    const r = await this.db.run(
      `UPDATE autogenerate_jobs SET consecutive_stt_failures = ?, consecutive_llm_failures = ?,
         updated_at_ms = ?
       WHERE id = ? AND locked_by = ? AND status = 'running'`,
      stt,
      llm,
      nowMs,
      jobId,
      workerId,
    );
    return r.changes;
  }

  async endJob(
    jobId: string,
    workerId: string,
    status: 'finished' | 'cancelled' | 'failed',
    stopReason: string | null,
    nowMs: number,
  ): Promise<number> {
    const r = await this.db.run(
      `UPDATE autogenerate_jobs SET status = ?, stop_reason = ?, finished_at_ms = ?,
         updated_at_ms = ?, locked_until_ms = NULL
       WHERE id = ? AND locked_by = ? AND status = 'running'`,
      status,
      stopReason,
      nowMs,
      nowMs,
      jobId,
      workerId,
    );
    return r.changes;
  }
}

async function resolveScopeOn(
  db: CatalogDb,
  teamId: string,
  scope: AutogenerateScope,
): Promise<AutogenerateScopeResult> {
  if ('showIds' in scope) {
    const ids = [...new Set(scope.showIds)];
    const shows = await db.all<{ id: string }>(
      `SELECT id FROM shows WHERE studio_id = ?
         AND id IN (SELECT v FROM json_array_elements_text(?::text::json) v)`,
      teamId,
      JSON.stringify(ids),
    );
    if (shows.length !== ids.length) return { ok: false, reason: 'show-not-found' };
    const rows = await db.all<Record<string, unknown>>(
      `SELECT s.id, s.show_id, ${EFFECTIVE_DATE} AS effective_date
       FROM sessions s
       WHERE s.ui_hidden = 0
         AND s.show_id IN (SELECT v FROM json_array_elements_text(?::text::json) v)
       ${CANDIDATE_ORDER}`,
      JSON.stringify(ids),
    );
    return { ok: true, sessions: rows.map(candidateFromRow) };
  }
  const ids = [...new Set(scope.sessionIds)];
  const rows = await db.all<Record<string, unknown>>(
    `SELECT s.id, s.show_id, ${EFFECTIVE_DATE} AS effective_date
     FROM sessions s JOIN shows sh ON sh.id = s.show_id
     WHERE sh.studio_id = ? AND s.ui_hidden = 0
       AND s.show_id IN (SELECT catalog.accessible_shows(catalog.app_user_id()))
       AND s.id IN (SELECT v FROM json_array_elements_text(?::text::json) v)
     ${CANDIDATE_ORDER}`,
    teamId,
    JSON.stringify(ids),
  );
  if (rows.length !== ids.length) return { ok: false, reason: 'session-not-found' };
  return { ok: true, sessions: rows.map(candidateFromRow) };
}

function candidateFromRow(r: Record<string, unknown>): AutogenerateCandidate {
  return {
    id: String(r.id),
    show_id: String(r.show_id),
    effective_date: (r.effective_date as string | null) ?? null,
  };
}
