import { keepPreviousData, useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { apiFetch } from '../client';
import type {
  AutogenerateDetailResponse,
  AutogenerateJobListResponse,
  AutogenerateJobResponse,
  AutogeneratePreviewResponse,
  AutogenerateScopeBody,
  AutogenerateStartBody,
} from '../types';

// --- Batch autogenerate hooks (batch-autogenerate D15; api-contract-freeze "Batch autogenerate
// endpoints") ---
//
// `enabled` is the section's visibility: nothing is fetched or polled while Settings is closed
// (the section is unmounted) or another section is shown. A live job's list and detail poll every
// 5 s, and only in a visible tab (TanStack's default: no background refetch interval). Errors
// surface as `ApiError`; the start's typed 409 bodies ride on its `body`.

export const AUTOGENERATE_POLL_MS = 5_000;

export const autogenerateKeys = {
  all: (teamId: string) => ['autogenerate-jobs', teamId] as const,
  list: (teamId: string) => ['autogenerate-jobs', teamId, 'list'] as const,
  detail: (teamId: string, jobId: string) => ['autogenerate-jobs', teamId, 'job', jobId] as const,
  preview: (teamId: string, body: AutogenerateScopeBody | null) =>
    ['autogenerate-jobs', teamId, 'preview', body] as const,
};

const base = (teamId: string) => `teams/${encodeURIComponent(teamId)}/autogenerate-jobs`;

export function useAutogeneratePreview(
  teamId: string,
  body: AutogenerateScopeBody | null,
  enabled: boolean,
) {
  return useQuery({
    queryKey: autogenerateKeys.preview(teamId, body),
    queryFn: () =>
      apiFetch<AutogeneratePreviewResponse>(`${base(teamId)}/preview`, {
        method: 'POST',
        body: JSON.stringify(body),
      }),
    enabled: enabled && teamId !== '' && body !== null,
    placeholderData: keepPreviousData,
  });
}

export function useAutogenerateJobs(teamId: string, enabled: boolean, poll: boolean) {
  return useQuery({
    queryKey: autogenerateKeys.list(teamId),
    queryFn: () => apiFetch<AutogenerateJobListResponse>(base(teamId)),
    enabled: enabled && teamId !== '',
    refetchInterval: enabled && poll ? AUTOGENERATE_POLL_MS : false,
  });
}

export function useAutogenerateJob(
  teamId: string,
  jobId: string | null,
  enabled: boolean,
  poll: boolean,
) {
  return useQuery({
    queryKey: autogenerateKeys.detail(teamId, jobId ?? ''),
    queryFn: () =>
      apiFetch<AutogenerateDetailResponse>(`${base(teamId)}/${encodeURIComponent(jobId ?? '')}`),
    enabled: enabled && teamId !== '' && jobId !== null,
    refetchInterval: enabled && poll ? AUTOGENERATE_POLL_MS : false,
  });
}

export function useStartAutogenerateJob(teamId: string) {
  const qc = useQueryClient();
  return useMutation({
    mutationFn: (body: AutogenerateStartBody) =>
      apiFetch<AutogenerateJobResponse>(base(teamId), {
        method: 'POST',
        body: JSON.stringify(body),
      }),
    onSettled: () => qc.invalidateQueries({ queryKey: autogenerateKeys.all(teamId) }),
  });
}

export function useCancelAutogenerateJob(teamId: string) {
  const qc = useQueryClient();
  return useMutation({
    mutationFn: (jobId: string) =>
      apiFetch<AutogenerateJobResponse>(`${base(teamId)}/${encodeURIComponent(jobId)}/cancel`, {
        method: 'POST',
      }),
    onSettled: () => qc.invalidateQueries({ queryKey: autogenerateKeys.all(teamId) }),
  });
}
