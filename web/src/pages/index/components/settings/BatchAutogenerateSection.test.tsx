describe('Settings › Batch autogenerate — start', () => {
  it('confirms with the sessions, max runs, own accounts and what auto-accept does', async () => {
    render();
    await within(panel()).findByText(/40 sessions/);
    fireEvent.click(startButton());
    const dialog = await screen.findByRole('alertdialog');
    const text = dialog.textContent ?? '';
    expect(text).toMatch(/40 sessions/);
    expect(text).toMatch(/at most 160 runs/);
    expect(text).toMatch(/your own provider accounts/);
    expect(text).toMatch(/added to wiki pages without review/);
    expect(text).toMatch(/remove or change text stay as suggestions/);
    expect(calls((p, m) => p.endsWith('autogenerate-jobs') && m === 'POST')).toHaveLength(0);
    fireEvent.click(within(dialog).getByRole('button', { name: 'Start' }));
    await waitFor(() =>
      expect(calls((p, m) => p.endsWith('autogenerate-jobs') && m === 'POST')).toHaveLength(1),
    );
    const body = JSON.parse(
      String(calls((p, m) => p.endsWith('autogenerate-jobs') && m === 'POST')[0]?.[1]?.body),
    );
    expect(body).toMatchObject({ expected_sessions: 40, wiki_mode: 'accept' });
  });

  it('pending mode leaves the auto-accept note out', async () => {
    render();
    await within(panel()).findByText(/40 sessions/);
    fireEvent.click(
      within(panel()).getByRole('radio', { name: 'Leave all as suggestions to review' }),
    );
    await waitFor(() =>
      expect(
        calls((p, m) => p.endsWith('/preview') && m === 'POST').some(
          ([, o]) => JSON.parse(String(o?.body)).wiki_mode === 'pending',
        ),
      ).toBe(true),
    );
    fireEvent.click(startButton());
    const dialog = await screen.findByRole('alertdialog');
    expect(dialog.textContent).not.toMatch(/without review/);
  });

  it('a 409 "sessions changed" refreshes the estimate and asks again', async () => {
    let n = 0;
    startReply = () => {
      n += 1;
      if (n === 1) {
        preview = { ...preview, sessions: 41, max_runs: 164 };
        throw new ApiError(409, 'The sessions changed since the estimate.', {
          detail: 'The sessions changed since the estimate.',
          sessions: 41,
        });
      }
      return { job: job({ status: 'queued' }) };
    };
    render();
    await within(panel()).findByText(/40 sessions/);
    fireEvent.click(startButton());
    fireEvent.click(
      within(await screen.findByRole('alertdialog')).getByRole('button', { name: 'Start' }),
    );
    await waitFor(() => expect(screen.getByRole('alertdialog').textContent).toMatch(/41 sessions/));
    expect(screen.getByRole('alertdialog').textContent).toMatch(/The sessions changed/);
  });

  it('a 422 shows a generic error', async () => {
    startReply = () => {
      throw new ApiError(422, '[]', { detail: [] });
    };
    render();
    await within(panel()).findByText(/40 sessions/);
    fireEvent.click(startButton());
    fireEvent.click(
      within(await screen.findByRole('alertdialog')).getByRole('button', { name: 'Start' }),
    );
    expect(await within(panel()).findByText('Could not start the batch job.')).toBeTruthy();
  });
});

describe('Settings › Batch autogenerate — a live job', () => {
  it('shows another admin’s job with its initiator, progress and Cancel instead of Start', async () => {
    jobs = [job()];
    render();
    const live = await within(panel()).findByTestId('autogenerate-live-job');
    expect(live.textContent).toMatch(/Bo Admin/);
    expect(live.textContent).toMatch(/1 of 4 steps/);
    expect(await within(live).findByText(/Episode Two/)).toBeTruthy();
    expect(within(panel()).queryByRole('button', { name: 'Start' })).toBeNull();
    fireEvent.click(within(live).getByRole('button', { name: 'Cancel job' }));
    const dialog = await screen.findByRole('alertdialog');
    expect(calls((p) => p.endsWith('/cancel'))).toHaveLength(0);
    fireEvent.click(within(dialog).getByRole('button', { name: 'Cancel job' }));
    await waitFor(() => expect(calls((p) => p.endsWith('/cancel'))).toHaveLength(1));
    expect(await within(live).findByText(/stopping after the current step/)).toBeTruthy();
  });

  it('polls every 5 s while the section is shown, and stops when another section is', async () => {
    vi.useFakeTimers({ shouldAdvanceTime: true });
    jobs = [job()];
    render();
    await within(panel()).findByTestId('autogenerate-live-job');
    const before = calls((p, m) => p.endsWith('/job-1') && m === 'GET').length;
    await act(async () => {
      await vi.advanceTimersByTimeAsync(5_100);
    });
    const after = calls((p, m) => p.endsWith('/job-1') && m === 'GET').length;
    expect(after).toBeGreaterThan(before);
    fireEvent.mouseDown(screen.getByRole('tab', { name: 'Account' }), { button: 0 });
    const hidden = autogenCalls().length;
    await act(async () => {
      await vi.advanceTimersByTimeAsync(15_000);
    });
    expect(autogenCalls().length).toBe(hidden);
  });
});

describe('Settings › Batch autogenerate — reports', () => {
  const words: Record<Exclude<AutogenerateStopReason, 'cancelled'>, RegExp> = {
    'initiator-unavailable': /account is no longer available/,
    'initiator-role-lost': /no longer an owner or admin/,
    'not-approved': /no longer an approved user/,
    'unconfigured-stt': /no speech-to-text key/,
    'unconfigured-llm': /no language model/,
    'provider-failing': /provider kept failing/,
  };

  it('groups failed and skipped items by session with details and the wiki counts', async () => {
    jobs = [
      job({ status: 'finished', finished_at_utc: '2026-11-09T11:00:00.000Z', current: null }),
    ];
    render();
    const report = await within(panel()).findByTestId('autogenerate-report');
    expect(report.textContent).toMatch(/Finished/);
    const one = within(report).getByTestId('autogenerate-report-s1');
    expect(one.textContent).toMatch(/Episode One/);
    expect(one.textContent).toMatch(/The session has no audio to transcribe\./);
    const two = within(report).getByTestId('autogenerate-report-s2');
    expect(two.textContent).toMatch(/The provider request failed\./);
    expect(report.textContent).toMatch(/2 added to the wiki, 1 left for review/);
  });

  it.each(Object.entries(words))('words the stop reason %s', async (reason, text) => {
    jobs = [
      job({
        status: 'failed',
        stop_reason: reason as AutogenerateStopReason,
        finished_at_utc: '2026-11-09T11:00:00.000Z',
        current: null,
      }),
    ];
    render();
    const report = await within(panel()).findByTestId('autogenerate-report');
    expect(report.textContent).toMatch(text);
  });

  it('Recent jobs opens a report', async () => {
    jobs = [
      job({ id: 'job-2', status: 'cancelled', stop_reason: 'cancelled', current: null }),
      job({ id: 'job-1', status: 'finished', current: null }),
    ];
    render();
    const recent = await within(panel()).findByRole('list', { name: 'Recent jobs' });
    fireEvent.click(within(recent).getAllByRole('button')[1] as HTMLElement);
    await waitFor(() =>
      expect(calls((p, m) => p.endsWith('/job-1') && m === 'GET').length).toBeGreaterThan(0),
    );
  });
});

