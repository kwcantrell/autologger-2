let jobs: AutogenerateJob[];
let preview: AutogeneratePreviewResponse;
let startReply: () => unknown;

function route() {
  mockedApiFetch.mockImplementation(async (path: string, opts?: RequestInit) => {
    const method = opts?.method ?? 'GET';
    if (path.startsWith('shows')) return { shows: SHOWS };
    const m = /^teams\/([^/]+)\/autogenerate-jobs(?:\/(.*))?$/.exec(path);
    if (m) {
      const rest = m[2];
      if (rest === 'preview' && method === 'POST') return preview;
      if (rest === undefined && method === 'GET') return { jobs };
      if (rest === undefined && method === 'POST') return startReply();
      if (rest?.endsWith('/cancel') && method === 'POST') {
        jobs = jobs.map((j) => ({ ...j, cancel_requested_by_name: 'Ana Diaz' }));
        return { job: jobs[0] };
      }
      if (rest && method === 'GET') {
        const j = jobs.find((x) => x.id === rest);
        if (j) return detail(j);
      }
    }
    throw new Error(`unexpected apiFetch: ${method} ${path}`);
  });
}

function Harness({ initial }: { initial: SettingsSectionId }) {
  const [section, setSection] = useState<SettingsSectionId>(initial);
  return (
    <SettingsView
      section={section}
      onSectionChange={setSection}
      onClose={vi.fn()}
      onCloseSession={vi.fn()}
      backLabel="Back to sessions"
    />
  );
}

function render(
  p: ProfilePayload = profile([['T1', 'Team One', 'admin']]),
  initial: SettingsSectionId = 'batch-autogenerate',
) {
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  client.setQueryData(['profile'], p);
  renderStrict(
    <QueryClientProvider client={client}>
      <Harness initial={initial} />
    </QueryClientProvider>,
  );
  return client;
}

