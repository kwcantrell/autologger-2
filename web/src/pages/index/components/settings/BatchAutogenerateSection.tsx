// --- Settings › Batch autogenerate (batch-autogenerate task 6.3, design D15; web-ui-system
// "Settings runs batch autogenerate for owners and admins") ---
//
// An owner or admin picks a team they manage, its shows, the steps and the wiki mode, reads a live
// estimate (the preview, debounced 400 ms) and starts a job behind a themed confirm. While the team
// has a live job the section shows it instead of Start (any manager's job, with Cancel), polled
// every 5 s while the section is shown; afterwards its report. Nothing is fetched while Settings
// is closed or another section is shown (`active`). The section acts immediately: no save bar.

const STOP_TEXT: Record<AutogenerateStopReason, string> = {
  cancelled: 'Cancelled.',
  'initiator-unavailable': "Stopped: the initiator's account is no longer available.",
  'initiator-role-lost': 'Stopped: the initiator is no longer an owner or admin of this team.',
  'not-approved': 'Stopped: the initiator is no longer an approved user on this server.',
  'unconfigured-stt': 'Stopped: the initiator has no speech-to-text key.',
  'unconfigured-llm': 'Stopped: the initiator has no language model.',
  'provider-failing': 'Stopped: the provider kept failing on three sessions in a row.',
};

const STATUS_TEXT: Record<AutogenerateJob['status'], string> = {
  queued: 'Queued',
  running: 'Running',
  finished: 'Finished',
  cancelled: 'Cancelled',
  failed: 'Stopped',
};

const isLive = (j: AutogenerateJob) => j.status === 'queued' || j.status === 'running';
const total = (j: AutogenerateJob) => Object.values(j.counts).reduce((a, b) => a + b, 0);
const ended = (j: AutogenerateJob) =>
  j.counts.done + j.counts.skipped + j.counts.failed + j.counts.cancelled;

function confirmMessage(
  p: AutogeneratePreviewResponse,
  mode: AutogenerateWikiMode,
  wiki: boolean,
  note?: string,
) {
  return (
    <AutogenerateConfirmMessage
      lead={[...(note ? [note] : []), `Run on ${p.sessions} sessions, at most ${p.max_runs} runs.`]}
      mode={mode}
      wiki={wiki}
    />
  );
}

export function BatchAutogenerateSection({ active = false }: SettingsSectionProps) {
  const { data: profile } = useProfile();
  const managed = useMemo(
    () =>
      (profile?.auth?.user?.teams ?? []).filter((t) => t.role === 'owner' || t.role === 'admin'),
    [profile],
  );
  const defaultTeam =
    managed.find((t) => t.id === profile?.active_studio_id)?.id ?? managed[0]?.id ?? '';
  const [picked, setPicked] = useState<string | null>(null);
  const teamId = picked ?? defaultTeam;

  const shows = useStudioShows(active && teamId ? teamId : null);
  const [excluded, setExcluded] = useState<Set<string>>(new Set());
  const [steps, setSteps] = useState<Set<AutogenerateStep>>(defaultAutogenerateSteps);
  const [mode, setMode] = useState<AutogenerateWikiMode>('accept');
  const [error, setError] = useState<string | null>(null);
  const [reportId, setReportId] = useState<string | null>(null);
  const { confirm, confirmElement } = useConfirm();

  const showList = shows.data?.shows ?? [];
  const selectedShows = showList.filter((s) => !excluded.has(s.id)).map((s) => s.id);
  const runSteps = orderedSteps(steps);
  const bodyKey = JSON.stringify([selectedShows, runSteps, mode]);
  // biome-ignore lint/correctness/useExhaustiveDependencies: the key is the body's content
  const body = useMemo<AutogenerateScopeBody | null>(
    () =>
      selectedShows.length === 0 || runSteps.length === 0
        ? null
        : { show_ids: selectedShows, steps: runSteps, wiki_mode: mode },
    [bodyKey],
  );
  const debounced = useDebounced(body, 400);

  const list = useAutogenerateJobs(teamId, active, false);
  const jobs = list.data?.jobs ?? [];
  const liveJob = jobs.find(isLive) ?? null;
  const live = useAutogenerateJob(teamId, liveJob?.id ?? null, active, liveJob !== null);
  // Poll the list too while a job is live, so its end is noticed.
  useAutogenerateJobs(teamId, active, liveJob !== null);
  const reportJobId = liveJob ? null : (reportId ?? jobs[0]?.id ?? null);
  const report = useAutogenerateJob(teamId, reportJobId, active, false);

  const preview = useAutogeneratePreview(teamId, debounced, active && liveJob === null);
  const start = useStartAutogenerateJob(teamId);
  const cancel = useCancelAutogenerateJob(teamId);

  if (managed.length === 0) {
    return (
      <SettingsSectionHeader
        title="Batch autogenerate"
        description="Only owners and admins of a team can run batch autogenerate."
      />
    );
  }

  const p = preview.data && debounced !== null ? preview.data : null;
  const startDisabled = body === null || p === null || p.blocked !== null || start.isPending;

  async function handleStart(current: AutogeneratePreviewResponse, note?: string) {
    if (body === null) return;
    const ok = await confirm({
      title: 'Start batch autogenerate',
      message: confirmMessage(current, mode, steps.has('wiki'), note),
      confirmLabel: 'Start',
    });
    if (!ok) return;
    setError(null);
    try {
      await start.mutateAsync({ ...body, expected_sessions: current.sessions });
      setReportId(null);
    } catch (err) {
      const changed = err instanceof ApiError ? (err.body as AutogenerateSessionsChanged) : null;
      if (err instanceof ApiError && err.status === 409 && typeof changed?.sessions === 'number') {
        const fresh = await preview.refetch();
        if (fresh.data) await handleStart(fresh.data, changed.detail);
        return;
      }
      if (err instanceof ApiError && err.status !== 422 && err.status < 500) {
        setError(err.message);
        return;
      }
      setError('Could not start the batch job.');
    }
  }

  async function handleCancel(job: AutogenerateJob) {
    const ok = await confirm({
      title: 'Cancel batch job',
      message: 'The job stops after its current step; the steps already done are kept.',
      confirmLabel: 'Cancel job',
      danger: true,
    });
    if (!ok) return;
    setError(null);
    try {
      await cancel.mutateAsync(job.id);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Could not cancel the batch job.');
    }
  }

  const teamOptions = managed.map((t) => ({ value: t.id, label: t.name }));

  return (
    <>
      <SettingsSectionHeader
        title="Batch autogenerate"
        description="Fill the missing transcripts, log events, topics and wiki updates of a team's sessions in one background job, oldest first."
      />
      <Card>
        <CardContent>
          <FieldGroup className="gap-5">
            <SettingRow label="Team" htmlFor="settings-batch-team">
              <Select
                id="settings-batch-team"
                value={teamId}
                options={teamOptions}
                onChange={(v) => {
                  setPicked(v);
                  setExcluded(new Set());
                  setReportId(null);
                }}
              />
            </SettingRow>

            <FieldSet>
              <FieldLegend variant="label">Shows</FieldLegend>
              {shows.isPending ? (
                <Spinner aria-hidden="true" />
              ) : showList.length === 0 ? (
                <FieldDescription>This team has no shows.</FieldDescription>
              ) : (
                <FieldGroup data-slot="checkbox-group" className="gap-3">
                  <Field orientation="horizontal">
                    <Checkbox
                      id="settings-batch-all-shows"
                      checked={excluded.size === 0}
                      onCheckedChange={(next) =>
                        setExcluded(next === true ? new Set() : new Set(showList.map((s) => s.id)))
                      }
                    />
                    <FieldLabel htmlFor="settings-batch-all-shows" className="font-normal">
                      All shows
                    </FieldLabel>
                  </Field>
                  {showList.map((s) => {
                    const id = `settings-batch-show-${s.id}`;
                    return (
                      <Field key={s.id} orientation="horizontal">
                        <Checkbox
                          id={id}
                          checked={!excluded.has(s.id)}
                          onCheckedChange={(next) => {
                            const ids = new Set(excluded);
                            if (next === true) ids.delete(s.id);
                            else ids.add(s.id);
                            setExcluded(ids);
                          }}
                        />
                        <FieldLabel htmlFor={id} className="font-normal">
                          {s.name}
                        </FieldLabel>
                      </Field>
                    );
                  })}
                </FieldGroup>
              )}
            </FieldSet>

            <AutogenerateOptions
              idPrefix="settings-batch"
              steps={steps}
              onStepsChange={setSteps}
              mode={mode}
              onModeChange={setMode}
            />
          </FieldGroup>
        </CardContent>
      </Card>

      {error && (
        <Alert variant="destructive">
          <TriangleAlertIcon aria-hidden="true" />
          <AlertDescription>{error}</AlertDescription>
        </Alert>
      )}

      {liveJob ? (
        <LiveJob
          job={live.data?.job ?? liveJob}
          detail={live.data ?? null}
          cancelling={cancel.isPending}
          onCancel={(j) => void handleCancel(j)}
        />
      ) : (
        <Card>
          <CardContent className="flex flex-col gap-3">
            {p === null ? (
              <FieldDescription>
                {body === null
                  ? 'Pick at least one show and one step.'
                  : 'Estimating the work to do…'}
              </FieldDescription>
            ) : (
              <>
                <p className="m-0 text-sm font-semibold">{`${p.sessions} sessions · at most ${p.max_runs} runs`}</p>
                <p className="m-0 text-sm text-muted-foreground">
                  {`Missing now: ${p.steps
                    .map((s) => `${stepLabel(s)} ${p.runs[s] ?? 0}`)
                    .join(', ')}`}
                </p>
                {p.blocked && (
                  <Alert>
                    <TriangleAlertIcon aria-hidden="true" />
                    <AlertDescription>{BLOCKED_TEXT[p.blocked]}</AlertDescription>
                  </Alert>
                )}
              </>
            )}
            <div>
              <Button
                type="button"
                disabled={startDisabled}
                onClick={() => p && void handleStart(p)}
              >
                {start.isPending && <Spinner data-icon="inline-start" aria-hidden="true" />}
                Start
              </Button>
            </div>
          </CardContent>
        </Card>
      )}

      {!liveJob && report.data && <Report detail={report.data} />}

      {jobs.length > 0 && (
        <Card>
          <CardContent className="flex flex-col gap-2">
            <h4 className="m-0 text-sm font-semibold">Recent jobs</h4>
            <ul aria-label="Recent jobs" className="m-0 flex list-none flex-col gap-1 p-0">
              {jobs.map((j) => (
                <li key={j.id}>
                  <Button
                    type="button"
                    variant="ghost"
                    size="sm"
                    aria-current={j.id === reportJobId || undefined}
                    onClick={() => setReportId(j.id)}
                  >
                    {`${fmtDateOnly(j.created_at_utc)} · ${STATUS_TEXT[j.status]} · ${j.initiator_name}`}
                  </Button>
                </li>
              ))}
            </ul>
          </CardContent>
        </Card>
      )}
      {confirmElement}
    </>
  );
}

function LiveJob({
  job,
  detail,
  cancelling,
  onCancel,
}: {
  job: AutogenerateJob;
  detail: AutogenerateDetailResponse | null;
  cancelling: boolean;
  onCancel: (job: AutogenerateJob) => void;
}) {
  const current = job.current
    ? detail?.sessions.find((s) => s.session_id === job.current?.session_id)
    : undefined;
  return (
    <Card data-testid="autogenerate-live-job">
      <CardContent className="flex flex-col gap-2">
        <p className="m-0 text-sm font-semibold">
          {`${STATUS_TEXT[job.status]} · started by ${job.initiator_name}`}
        </p>
        <p className="m-0 text-sm">{`${ended(job)} of ${total(job)} steps · ${job.sessions} sessions`}</p>
        {job.current && current && (
          <p className="m-0 text-sm text-muted-foreground">
            {`Now: ${current.title || 'Untitled session'} · ${stepLabel(job.current.step)}`}
          </p>
        )}
        {job.cancel_requested_by_name ? (
          <p className="m-0 text-sm text-muted-foreground">
            {`Cancel requested by ${job.cancel_requested_by_name}; stopping after the current step.`}
          </p>
        ) : (
          <div>
            <Button
              type="button"
              variant="outline"
              disabled={cancelling}
              onClick={() => onCancel(job)}
            >
              {cancelling && <Spinner data-icon="inline-start" aria-hidden="true" />}
              Cancel job
            </Button>
          </div>
        )}
      </CardContent>
    </Card>
  );
}

function Report({ detail }: { detail: AutogenerateDetailResponse }) {
  const { job } = detail;
  let accepted = 0;
  let pending = 0;
  let hasWiki = false;
  for (const s of detail.sessions) {
    for (const i of s.steps) {
      if (i.wiki_accepted !== null || i.wiki_pending !== null) hasWiki = true;
      accepted += i.wiki_accepted ?? 0;
      pending += i.wiki_pending ?? 0;
    }
  }
  const problems = detail.sessions
    .map((s) => ({
      s,
      items: s.steps.filter((i) => i.status === 'skipped' || i.status === 'failed'),
    }))
    .filter((x) => x.items.length > 0);
  return (
    <Card data-testid="autogenerate-report">
      <CardContent className="flex flex-col gap-3">
        <p className="m-0 text-sm font-semibold">
          {`${STATUS_TEXT[job.status]} · ${job.sessions} sessions · started by ${job.initiator_name}`}
        </p>
        {job.stop_reason && <p className="m-0 text-sm">{STOP_TEXT[job.stop_reason]}</p>}
        <FieldContent>
          <FieldDescription>
            {`${job.counts.done} done, ${job.counts.skipped} skipped, ${job.counts.failed} failed, ${job.counts.cancelled} cancelled.`}
          </FieldDescription>
          {hasWiki && (
            <FieldDescription>{`${accepted} added to the wiki, ${pending} left for review.`}</FieldDescription>
          )}
        </FieldContent>
        {problems.length > 0 && (
          <ul className="m-0 flex list-none flex-col gap-2 p-0">
            {problems.map(({ s, items }) => (
              <li key={s.session_id} data-testid={`autogenerate-report-${s.session_id}`}>
                <p className="m-0 text-sm font-medium">{s.title || 'Session no longer exists'}</p>
                <ul className="m-0 list-disc pl-5 text-sm text-muted-foreground">
                  {items.map((i) => (
                    <li key={i.step}>{`${stepLabel(i.step)}: ${i.detail ?? i.status}`}</li>
                  ))}
                </ul>
              </li>
            ))}
          </ul>
        )}
      </CardContent>
    </Card>
  );
}
